import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart

def send_ticket_email(to_email, farmer_name, ticket_details):
    """
    Automated Email Notification Sender for AgriSolve Portal
    """
    # Sender Configuration (Testing ke liye Gmail SMTP use hoga)
    SENDER_EMAIL = "ts0151253@gmail.com"  # Apna Gmail address yahan likhein
    SENDER_PASSWORD = "soqt mshz bbeh dsrx"   # Gmail App Password (Normal password nahi)
    
    subject = f"🎫 [AgriSolve] Ticket Confirmation - {ticket_details['ticket_id']}"
    
    # Email Body (HTML Formatted)
    html_content = f"""
    <html>
    <body style="font-family: Arial, sans-serif; color: #333;">
        <div style="background-color: #1b5e20; padding: 15px; color: white; border-radius: 5px;">
            <h2>🌾 AgriSolve - Farmer Grievance Ticket Confirmation</h2>
        </div>
        <div style="padding: 15px; border: 1px solid #ddd; margin-top: 10px;">
            <p>Dear <b>{farmer_name if farmer_name else 'Citizen'}</b>,</p>
            <p>Aapki grievance query success-fully receive aur auto-route kar di gayi hai.</p>
            
            <h3>Ticket Details:</h3>
            <ul>
                <li><b>Ticket Reference ID:</b> {ticket_details['ticket_id']}</li>
                <li><b>Assigned Department:</b> {ticket_details['department']}</li>
                <li><b>Priority Level:</b> {ticket_details['priority']}</li>
                <li><b>NLP Confidence Score:</b> {ticket_details['confidence_score']}%</li>
            </ul>
            
            <p><b>Matched Governance Policy:</b> {ticket_details['matched_policy_doc']}</p>
            <p><b>Action Taken:</b> {ticket_details['suggested_action']}</p>
            
            <hr>
            <p style="font-size: 0.8em; color: #666;">
                <i>This is an automated message generated by the Air-Gapped AgriSolve Engine. Please do not reply directly to this email.</i>
            </p>
        </div>
    </body>
    </html>
    """
    
    try:
        msg = MIMEMultipart('alternative')
        msg['From'] = SENDER_EMAIL
        msg['To'] = to_email
        msg['Subject'] = subject
        msg.attach(MIMEText(html_content, 'html'))
        
        # Connect to Gmail SMTP Server
        server = smtplib.SMTP('smtp.gmail.com', 587)
        server.starttls()
        server.login(SENDER_EMAIL, SENDER_PASSWORD)
        server.sendmail(SENDER_EMAIL, to_email, msg.as_string())
        server.quit()
        return True, "Email sent successfully!"
    except Exception as e:
        return False, str(e)